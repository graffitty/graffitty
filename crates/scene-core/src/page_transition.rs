//! Full-page push/pop motion shared by every mobile frontend.
//!
//! Reference: a stock UINavigationController on the iOS 26.3 simulator,
//! sampled via CADisplayLink and CALayer.presentation(). See the reproducible
//! probe and measurements in docs/developers/architecture/mobile-navigation.md.

/// UIKit's nominal coordinator duration is 350 ms; its visible spring settles
/// over 28 frames at 60 Hz. Keep the tail instead of cutting it at 350 ms.
pub const DURATION: f64 = 28.0 / 60.0;
const OMEGA: f64 = std::f64::consts::TAU / 0.3;
const INITIAL_VELOCITY: f64 = 8.78;

#[derive(Clone, Copy, Debug)]
pub struct Frame {
    /// Screen-width displacement of the workspace, above the server list.
    pub workspace: f64,
    /// Screen-width displacement of the server list, below the workspace.
    pub list: f64,
    pub shade: f64,
    pub done: bool,
}

/// Absolute elapsed time makes 30, 60 and 120 Hz clients follow the same curve.
/// Both directions start at rest in the UI; the fitted spring reproduces the
/// first visible UIKit frame, including its nonzero initial presentation speed.
pub fn sample(elapsed: f64, entering: bool) -> Frame {
    let time = if elapsed.is_finite() {
        elapsed.max(0.0)
    } else {
        DURATION
    };
    let done = time >= DURATION;
    let progress = if done {
        1.0
    } else {
        1.0 - (1.0 + (OMEGA - INITIAL_VELOCITY) * time) * (-OMEGA * time).exp()
    };
    let covered = if entering { progress } else { 1.0 - progress };
    Frame {
        workspace: 1.0 - covered,
        list: -0.3 * covered,
        shade: 0.1 * covered,
        done,
    }
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn endpoints_and_directions_match() {
        for entering in [false, true] {
            let start = sample(0.0, entering);
            let end = sample(DURATION, entering);
            assert!(!start.done && end.done);
            assert_eq!(start.workspace, if entering { 1.0 } else { 0.0 });
            assert_eq!(end.workspace, if entering { 0.0 } else { 1.0 });
            assert_eq!(end.list, if entering { -0.3 } else { 0.0 });
            for frame in 0..=120 {
                let t = DURATION * frame as f64 / 120.0;
                let a = sample(t, true);
                let b = sample(t, false);
                assert!((a.workspace + b.workspace - 1.0).abs() < 1e-12);
                assert!((a.list + b.list + 0.3).abs() < 1e-12);
                assert!((0.0..=1.0).contains(&a.workspace));
            }
        }
    }

    #[test]
    fn matches_native_presentation_samples() {
        // Stock UIKit pop: first visible motion starts at t=0.010644 after
        // the coordinator callback. Width=402 pt. These are measured frames,
        // not values generated by the implementation under test.
        for (time, x) in [
            (0.043952125, 120.859355011),
            (0.093966875, 260.631707758),
            (0.160625292, 352.912901760),
            (0.243974458, 390.353861741),
            (0.343958292, 400.111266530),
        ] {
            let actual = sample(time - 0.010644, false).workspace * 402.0;
            assert!((actual - x).abs() < 0.35, "{time}: {actual} vs {x}");
        }
    }

    #[test]
    fn elapsed_time_has_no_frame_rate_dependency_or_overshoot() {
        for hz in [30, 60, 120] {
            let mut previous = 1.0;
            for frame in 0..=hz {
                let value = sample(frame as f64 / hz as f64, true);
                assert!(value.workspace <= previous);
                previous = value.workspace;
            }
            assert_eq!(previous, 0.0);
        }
        assert_eq!(sample(-1.0, true).workspace, 1.0);
        assert!(sample(f64::NAN, true).done);
    }
}
